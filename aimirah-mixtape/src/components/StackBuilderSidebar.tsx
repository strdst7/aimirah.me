import React, { useState } from 'react';
import { CLI_PACKAGE, formatComponentTitle, stripExt } from '../data/catalog';
import { CartState, ComponentTypePlural } from '../types/catalog';
import { TYPE_META } from './Icons';

export function buildStackInstallCommand(cart: CartState): string {
  let cmd = CLI_PACKAGE;
  for (const [typeKey, items] of Object.entries(cart) as [ComponentTypePlural, CartState[ComponentTypePlural]][]) {
    if (items && items.length > 0) {
      const meta = TYPE_META[typeKey];
      if (meta) {
        const joined = items.map((i) => stripExt(i.path)).join(',');
        cmd += ` ${meta.flag} ${joined}`;
      }
    }
  }
  return cmd;
}

export const StackBuilderSidebar: React.FC<{
  open: boolean;
  onOpen: () => void;
  onClose: () => void;
  cart: CartState;
  onRemoveItem: (path: string, typePlural: ComponentTypePlural) => void;
  onClearAll: () => void;
  onSaveStackAsCollection: (name: string) => void;
  onNotify: (msg: string) => void;
}> = ({
  open,
  onOpen,
  onClose,
  cart,
  onRemoveItem,
  onClearAll,
  onSaveStackAsCollection,
  onNotify,
}) => {
  const [copied, setCopied] = useState(false);
  const [savePromptOpen, setSavePromptOpen] = useState(false);
  const [mixtapeName, setMixtapeName] = useState('');

  const totalCount = Object.values(cart).reduce((acc, list) => acc + (list?.length ?? 0), 0);
  const command = buildStackInstallCommand(cart);

  const handleCopy = () => {
    navigator.clipboard?.writeText(command);
    setCopied(true);
    onNotify('Copied multi-track Mixtape CLI command!');
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownloadScript = () => {
    const content = `#!/usr/bin/env bash
# Generated by aimirah.mixtape — Ready-to-use Claude Code Stack
set -euo pipefail

echo "▶ Installing aimirah.mixtape stack (${totalCount} components)..."
${command}
echo "✓ Mixtape installation complete!"
`;
    const blob = new Blob([content], { type: 'text/x-shellscript' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'install-aimirah-mixtape.sh';
    a.click();
    URL.revokeObjectURL(url);
    onNotify('Downloaded install-aimirah-mixtape.sh');
  };

  const handleShare = () => {
    const text = `Check out my Claude Code mixtape stack (${totalCount} tracks)!\n\n${command}\n\nMix yours at https://aimirah.mixtape`;
    window.open(
      `https://twitter.com/intent/tweet?text=${encodeURIComponent(text)}`,
      '_blank',
      'noopener,noreferrer'
    );
  };

  const handleSaveCollection = (e: React.FormEvent) => {
    e.preventDefault();
    if (!mixtapeName.trim()) return;
    onSaveStackAsCollection(mixtapeName.trim());
    setMixtapeName('');
    setSavePromptOpen(false);
  };

  const nonEmptyGroups = (
    Object.entries(cart) as [ComponentTypePlural, CartState[ComponentTypePlural]][]
  ).filter(([, list]) => list && list.length > 0);

  return (
    <>
      {/* Floating Stack Pill when closed and non-empty */}
      {totalCount > 0 && !open && (
        <button
          type="button"
          onClick={onOpen}
          className="fixed bottom-6 right-6 z-40 flex items-center gap-2.5 pl-4 pr-3 py-3 bg-[var(--color-accent)] hover:bg-[var(--color-accent-hover)] text-white rounded-[4px] shadow-[0_5px_18px_rgba(0,0,0,.32)] transition-all duration-200 hover:scale-[1.03] active:translate-y-px cursor-pointer"
        >
          <svg className="w-4 h-4" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth="2">
            <path
              strokeLinecap="round"
              strokeLinejoin="round"
              d="M20 7l-8-4-8 4m16 0l-8 4m8-4v10l-8 4m0-10L4 7m8 4v10M4 7v10l8 4"
            />
          </svg>
          <span className="text-[13px] font-mono font-semibold">Stack</span>
          <span className="min-w-5 h-5 px-1.5 rounded-full bg-white/25 text-white text-[11px] font-mono font-bold flex items-center justify-center border border-white/25">
            {totalCount}
          </span>
        </button>
      )}

      {/* Backdrop */}
      {open && (
        <div
          className="fixed inset-0 bg-black/60 backdrop-blur-xs z-40 transition-opacity"
          onClick={onClose}
        />
      )}

      {/* Right Slide-Over Drawer */}
      <div
        className={`fixed top-0 right-0 h-full w-96 max-w-[92vw] bg-[var(--color-surface-0)] border-l border-[var(--color-border)] shadow-2xl z-50 transform transition-transform duration-300 ease-out flex flex-col ${
          open ? 'translate-x-0' : 'translate-x-full pointer-events-none'
        }`}
      >
        {/* Header — a milled top plate */}
        <div className="flex items-center justify-between px-4 py-4 border-b-2 border-[var(--color-border-strong)] brushed bg-[var(--color-surface-1)] shrink-0 shadow-[0_2px_6px_rgba(0,0,0,.14)]">
          <div className="flex items-center gap-3">
            <div className="w-9 h-9 rounded-[3px] bg-[var(--color-accent)] flex items-center justify-center shadow-[inset_0_1px_0_rgba(255,255,255,.4),0_2px_5px_rgba(0,0,0,.3)]">
              <svg className="w-4.5 h-4.5 text-white" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth="2">
                <path
                  strokeLinecap="round"
                  strokeLinejoin="round"
                  d="M20 7l-8-4-8 4m16 0l-8 4m8-4v10l-8 4m0-10L4 7m8 4v10M4 7v10l8 4"
                />
              </svg>
            </div>
            <div className="flex flex-col">
              <h2 className="text-[17px] leading-none text-[var(--color-text-primary)]">
                <span className="liner">Dub Queue</span>
              </h2>
              <span className="legend mt-1" style={{ fontSize: 9 }}>
                {totalCount} {totalCount === 1 ? 'track' : 'tracks'} armed
              </span>
            </div>
          </div>

          <div className="flex items-center gap-1.5">
            {totalCount > 0 && (
              <button
                type="button"
                onClick={onClearAll}
                className="text-xs font-mono text-[var(--color-text-tertiary)] hover:text-red-400 hover:bg-red-400/10 px-2.5 py-1.5 rounded-lg transition-all font-medium cursor-pointer"
              >
                Clear All
              </button>
            )}
            <button
              type="button"
              onClick={onClose}
              aria-label="Close Stack Builder"
              className="p-2 rounded-lg hover:bg-[var(--color-surface-3)] text-[var(--color-text-secondary)] hover:text-[var(--color-text-primary)] transition-colors cursor-pointer"
            >
              <svg className="w-4 h-4" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth="2">
                <path strokeLinecap="round" strokeLinejoin="round" d="M6 18L18 6M6 6l12 12" />
              </svg>
            </button>
          </div>
        </div>

        {/* Body */}
        <div className="flex-1 overflow-y-auto min-h-0">
          {totalCount === 0 ? (
            <div className="flex flex-col items-center justify-center h-full text-center px-6">
              <div className="relative w-24 h-24 rounded-2xl bg-gradient-to-br from-[var(--color-surface-2)] to-[var(--color-surface-3)] border border-[var(--color-border)] flex items-center justify-center mb-5 shadow-xs">
                <svg className="w-11 h-11 text-[var(--color-text-tertiary)]" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth="1.5">
                  <path
                    strokeLinecap="round"
                    strokeLinejoin="round"
                    d="M20 7l-8-4-8 4m16 0l-8 4m8-4v10l-8 4m0-10L4 7m8 4v10M4 7v10l8 4"
                  />
                </svg>
                <div className="absolute -top-1.5 -right-1.5 w-7 h-7 rounded-full bg-[var(--color-accent)]/15 border-2 border-[var(--color-accent)]/40 flex items-center justify-center">
                  <span className="text-[var(--color-accent)] font-mono text-sm font-bold">+</span>
                </div>
              </div>
              <p className="text-base font-mono font-semibold text-[var(--color-text-primary)] mb-2">
                Your mixtape stack is empty
              </p>
              <p className="text-[13px] text-[var(--color-text-secondary)] max-w-xs leading-relaxed">
                Browse components and click the{' '}
                <span className="inline-flex items-center justify-center w-4 h-4 rounded bg-[var(--color-accent)]/15 text-[var(--color-accent)] text-[11px] font-mono font-bold mx-0.5">
                  +
                </span>{' '}
                button on any card to bundle multiple agents, skills, hooks, and MCPs into one CLI command.
              </p>
            </div>
          ) : (
            <div className="px-3.5 py-4">
              {nonEmptyGroups.map(([typeKey, list], gIdx) => {
                const meta = TYPE_META[typeKey];
                const isLastGroup = gIdx === nonEmptyGroups.length - 1;
                return (
                  <div
                    key={typeKey}
                    className={isLastGroup ? 'mb-2' : 'mb-4 pb-3 border-b border-[var(--color-border)]'}
                  >
                    <div className="flex items-center gap-2.5 py-2 px-3 rounded-lg bg-[var(--color-surface-1)] border border-[var(--color-border)] mb-2">
                      <svg
                        className="w-4 h-4 shrink-0"
                        style={{ color: meta.color }}
                        fill="none"
                        viewBox="0 0 24 24"
                        stroke="currentColor"
                        strokeWidth="1.75"
                      >
                        <path
                          strokeLinecap="round"
                          strokeLinejoin="round"
                          d="M22 19a2 2 0 01-2 2H4a2 2 0 01-2-2V5a2 2 0 012-2h5l2 3h9a2 2 0 012 2z"
                        />
                      </svg>
                      <span className="text-[13px] font-mono font-semibold text-[var(--color-text-primary)]">
                        {meta.label}
                      </span>
                      <span className="ml-auto text-[10px] font-mono px-2 py-0.5 rounded-full bg-[var(--color-surface-3)] text-[var(--color-text-tertiary)] font-semibold tabular-nums border border-[var(--color-border)]">
                        {list.length}
                      </span>
                    </div>

                    {list.map((entry, idx) => {
                      const isLast = idx === list.length - 1;
                      return (
                        <div
                          key={entry.path}
                          className="flex items-center group pl-2 pr-1.5 py-0.5 hover:bg-[var(--color-surface-1)] rounded-md transition-colors"
                        >
                          <span className="text-[var(--color-border-strong)] text-[13px] font-mono w-7 shrink-0 select-none">
                            {isLast ? '└─' : '├─'}
                          </span>
                          <svg
                            className="w-3.5 h-3.5 shrink-0 mr-2 text-[var(--color-text-tertiary)]"
                            fill="none"
                            viewBox="0 0 24 24"
                            stroke="currentColor"
                            strokeWidth="1.5"
                          >
                            <path d="M14 2H6a2 2 0 00-2 2v16a2 2 0 002 2h12a2 2 0 002-2V8z" />
                            <polyline points="14 2 14 8 20 8" />
                          </svg>
                          <span className="text-[12px] font-mono text-[var(--color-text-primary)] flex-1 truncate py-1.5 font-medium">
                            {formatComponentTitle(entry.name)}
                          </span>
                          <button
                            type="button"
                            onClick={() => onRemoveItem(entry.path, typeKey)}
                            title="Remove from stack"
                            className="opacity-70 group-hover:opacity-100 p-1.5 rounded-md hover:bg-red-400/10 text-[var(--color-text-tertiary)] hover:text-red-400 transition-all shrink-0 cursor-pointer"
                          >
                            <svg className="w-3.5 h-3.5" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth="2">
                              <path strokeLinecap="round" strokeLinejoin="round" d="M6 18L18 6M6 6l12 12" />
                            </svg>
                          </button>
                        </div>
                      );
                    })}
                  </div>
                );
              })}
            </div>
          )}
        </div>

        {/* Sticky Footer Command Builder */}
        {totalCount > 0 && (
          <div className="border-t border-[var(--color-border)] bg-gradient-to-t from-[var(--color-surface-1)] to-[var(--color-surface-0)] p-4 space-y-3 shrink-0">
            <div className="space-y-2">
              <div className="flex items-center justify-between">
                <span className="text-[11px] font-mono text-[var(--color-text-tertiary)] font-semibold uppercase tracking-wide">
                  Installation Command
                </span>
                <button
                  type="button"
                  onClick={() => setSavePromptOpen((v) => !v)}
                  className="text-[11px] font-mono text-[var(--color-accent)] hover:underline cursor-pointer"
                >
                  {savePromptOpen ? 'Cancel' : '+ Save as Mixtape'}
                </button>
              </div>

              {savePromptOpen && (
                <form onSubmit={handleSaveCollection} className="flex gap-1.5">
                  <input
                    type="text"
                    placeholder="e.g. Side C · API Microservices"
                    value={mixtapeName}
                    onChange={(e) => setMixtapeName(e.target.value)}
                    className="flex-1 min-w-0 bg-[var(--color-surface-2)] border border-[var(--color-border)] rounded px-2.5 py-1.5 text-xs font-mono text-[var(--color-text-primary)] outline-none focus:border-[var(--color-accent)]"
                  />
                  <button
                    type="submit"
                    className="px-3 py-1.5 rounded bg-[var(--color-accent)] text-white text-xs font-mono font-semibold cursor-pointer"
                  >
                    Save
                  </button>
                </form>
              )}

              <div className="counter-window rounded-[3px] p-3 max-h-32 overflow-y-auto">
                <code
                  className="text-[11.5px] font-mono break-all leading-relaxed block"
                  style={{
                    color: 'var(--color-display-amber)',
                    textShadow: '0 0 8px rgba(255,180,84,.45)',
                  }}
                >
                  {command}
                </code>
              </div>
            </div>

            <button
              type="button"
              onClick={handleCopy}
              className="transport w-full py-2.5 px-4 rounded-[3px] bg-[var(--color-accent)] hover:bg-[var(--color-accent-hover)] text-white font-mono text-[13px] font-bold tracking-wide uppercase transition-all active:scale-[0.99] cursor-pointer"
            >
              {copied ? '✓ Copied Mixtape Command!' : 'Copy Installation Command'}
            </button>

            <div className="grid grid-cols-2 gap-2">
              <button
                type="button"
                onClick={handleDownloadScript}
                className="py-2 px-3 rounded-lg bg-[var(--color-surface-2)] hover:bg-[var(--color-surface-3)] border border-[var(--color-border)] text-xs font-mono text-[var(--color-text-secondary)] hover:text-[var(--color-text-primary)] transition-colors cursor-pointer"
              >
                ↓ Export .sh
              </button>
              <button
                type="button"
                onClick={handleShare}
                className="py-2 px-3 rounded-lg bg-[var(--color-surface-2)] hover:bg-[var(--color-surface-3)] border border-[var(--color-border)] text-xs font-mono text-[var(--color-text-secondary)] hover:text-[var(--color-text-primary)] transition-colors cursor-pointer"
              >
                Share on X ↗
              </button>
            </div>
          </div>
        )}
      </div>
    </>
  );
};
